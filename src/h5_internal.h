/*
 * h5_internal.h - private definitions shared by the library and its tests.
 *
 * Not part of the public API. Tests include this to inspect context state
 * that the public header deliberately hides.
 */

#ifndef HIVE_V_H5_INTERNAL_H
#define HIVE_V_H5_INTERNAL_H

#include "h5.h"
#include "h5_fixed.h"
#include <stdint.h>

/* Full sine period, one entry per sample of a 4096-step cycle. */
#define H5_SINE_TABLE_SIZE 4096

/* First quadrant plus both endpoints: indices 0..1024 inclusive. Stored in
 * flash; the other quadrants are mirrored and negated at run time. */
#define H5_SINE_QUAD_SIZE 1025

/* Description of one (voice, param) entry. */
struct h5_param_info {
    int32_t min;
    int32_t max;
    int32_t default_value;
    bool supported;
};

/* Single source of truth for parameter ranges, defaults and support. */
extern const struct h5_param_info h5_param_table[H5_VOICE_COUNT][H5_PARAM_COUNT];

/* First quadrant of the sine, Q15, for i = 0..1024. This is the only sine
 * data stored in the image; every other entry is derived from it. */
extern const int16_t h5_sine_quad1[H5_SINE_QUAD_SIZE];

/* The full 4096-entry period, allocated and rebuilt from h5_sine_quad1 on the
 * first h5_create_context(). Shared by every context. Null when the
 * allocation failed; the lookups then fall back to the quadrant. */
extern int16_t *h5_sine;

/* Allocate and rebuild the full sine period. Idempotent and meant to be
 * called once, before any lookup. */
void h5_sine_init(void);

/* Q15 sine of 2*pi*i/4096 for any index, using the rebuilt table when it is
 * available and the quadrant fallback otherwise. The index must be 0..4095. */
static inline int16_t h5_sine_at(uint32_t index)
{
    if (h5_sine != 0) {
        return h5_sine[index];
    }
    if (index <= 1024u) {
        return h5_sine_quad1[index];
    }
    if (index <= 2047u) {
        return h5_sine_quad1[2048u - index];
    }
    if (index <= 3071u) {
        return (int16_t)-h5_sine_quad1[index - 2048u];
    }
    return (int16_t)-h5_sine_quad1[4096u - index];
}

/* Sine interpolation, linear, from the shared table. The 28-bit phase
 * covers one full period; the output is Q31 with the table's amplitude
 * scale (peak 32767 << 16). Exact at integer table indices. */
int32_t h5_sine_interp(uint32_t phase);

/* tan(pi * f / sr) as Q16 from the shared sine table (no libm). Used for
 * the one-pole pre-filter coefficients at parameter change only. */
int32_t h5_tanpi_q16(int32_t f_q16, uint32_t sample_rate);

/* Semitone ratio table: 2^(n/12) as Q16.16 for n = -62..+62. Index n + 62.
 * Generated by tools/gen_semitone_table.py, round-half-up. */
#define H5_SEMITONE_MAX 62
#define H5_SEMITONE_COUNT (2 * H5_SEMITONE_MAX + 1)
extern const int32_t h5_semitone[H5_SEMITONE_COUNT];

/* Lookup with clamping: semitones outside [-62, +62] return the table end
 * value. */
int32_t h5_semitone_ratio(int semitones);

/* Fractional lookup: semitones_q16 is a signed Q16.16 semitone count,
 * linearly interpolated between the table entries and clamped to the table
 * range. */
int32_t h5_semitone_ratio_interp(int32_t semitones_q16);

/* x^0.7 as Q16.16 for x in [0, 1], from a 65-entry table (step 1/64) with
 * linear interpolation. Used for the drum voices' NoiseTone and Click
 * power-law mappings, which are evaluated only on parameter change. */
#define H5_POW07_SIZE 65
extern const int32_t h5_pow07[H5_POW07_SIZE];
int32_t h5_pow07_q16(int32_t x_q16);

/* Soft-clip shaper table: tanh(u) as Q15 for u = j/H5_SOFTCLIP_STEPS,
 * j = 0..H5_SOFTCLIP_SIZE-1. The input magnitude is at most 2^31 (a
 * saturated Q30 sample with the headroom bit), so u stays in [0, 1] and the
 * table ends at tanh(1) ~= 0.76159. Generated by
 * tools/gen_softclip_table.py, round-half-up. Negative arguments use odd
 * symmetry. The engine's 1.5 output gain is applied by the caller after the
 * table lookup, so the result lives in Q30 with headroom to 2.0. */
#define H5_SOFTCLIP_SIZE 49
#define H5_SOFTCLIP_STEPS 48
extern const int16_t h5_softclip[H5_SOFTCLIP_SIZE];

/* Shaper: 1.5 * tanh(u) in Q30, with u = |m| / 2^31 for the Q30 engine mix
 * m (the mix keeps one headroom bit, so |m| <= 2^31 maps to u in [0, 1]).
 * Odd-symmetric. */
int32_t h5_softclip_q31(int32_t m);

/* Per-voice noise generator state. */
struct h5_noise_s {
    uint32_t x;      /* LCG state */
    uint32_t divider; /* hold length: max(1, sr/48000) */
    uint32_t phase;  /* position in the hold cycle */
    int32_t held;    /* held value, Q31 */
};

/* Initialise a noise generator with an explicit seed. A seed of 0 becomes
 * 1. */
void h5_noise_init(struct h5_noise_s *n, uint32_t seed, uint32_t sample_rate);

/* Initialise a noise generator with the per-voice default seed (distinct
 * and non-zero per voice). */
void h5_noise_init_voice(struct h5_noise_s *n, h5_voice voice,
    uint32_t sample_rate);

/* Advance one output sample and return the held value, Q31 in [-1, 1). */
int32_t h5_noise_next(struct h5_noise_s *n);

/* Envelope phases. */
enum {
    H5_ENV_DONE = 0,
    H5_ENV_ATTACK,
    H5_ENV_RELEASE
};

/* Linear AR envelope state, Q30. 1.0 is exactly 1 << 30, so the peak is
 * representable. */
struct h5_env_s {
    int32_t value;      /* Q30 */
    int32_t delta_a;    /* Q30 per sample, attack */
    int32_t delta_r;    /* Q30 per sample, release */
    int32_t attack_len; /* attack length in samples */
    int32_t release_len; /* release length in samples */
    int32_t count;      /* samples elapsed in the current phase */
    int32_t state;      /* H5_ENV_* */
};

void h5_env_init(struct h5_env_s *e);

/* Set the envelope times. Times are Q16 seconds, clipped non-negative;
 * lengths are truncated to samples with a floor of 1. Running phases keep
 * running with the new deltas. */
void h5_env_set_times(struct h5_env_s *e, int32_t attack_q16,
    int32_t release_q16, uint32_t sample_rate);

/* Restart from the start of the attack. */
void h5_env_trigger(struct h5_env_s *e);

/* Advance one sample and return the Q30 envelope value. */
int32_t h5_env_next(struct h5_env_s *e);

/* Filter modes for h5_svf_set(). */
enum {
    H5_SVF_LP = 0,
    H5_SVF_BP,
    H5_SVF_HP
};

/* Second-order resonant filter, direct-form I. Coefficients are Q30
 * (Q31 samples, 64-bit products); a1 approaches -2. */
struct h5_svf_s {
    int32_t b0, b1, b2; /* Q30 numerators */
    int32_t a1, a2;     /* Q30 normalised denominators */
    int32_t x1, x2, y1, y2; /* Q31 state */
    int32_t mode;       /* H5_SVF_*; the run loop folds the feed-forward
                         * per mode (b1/b2 are redundant with b0) */
};

void h5_svf_reset(struct h5_svf_s *f);

/* Compute all coefficients for one mode. cutoff_q16 is Q16 Hz and is
 * clamped below 0.49 * sample_rate; q_q16 is Q16 and clamped to [0.5, 16].
 * Trivially cheap; call only on parameter change. */
void h5_svf_set(struct h5_svf_s *f, int mode, int32_t cutoff_q16,
    int32_t q_q16, uint32_t sample_rate);

/* Recompute the coefficients without touching the filter state. Used by
 * engines whose cutoff is swept per sample. */
void h5_svf_tune(struct h5_svf_s *f, int mode, int32_t cutoff_q16,
    int32_t q_q16, uint32_t sample_rate);

/* Advance one sample and return the Q31 output of the configured mode. */
int32_t h5_svf_run(struct h5_svf_s *f, int32_t x);

/* Kick voice runtime state. The engine keeps its own copies of the parameters
 * it needs per sample so the audio path never reads the parameter matrix.
 * Engine outputs are Q30 (1.0 = 1 << 30) with one headroom bit for the
 * shaper stage's overshoot; the mixer converts. */
struct h5_kick_s {
    struct h5_env_s env_noise;  /* noise AR: ~2 ms attack, NoiseDecay release */
    struct h5_env_s env_tone;   /* tone AR: 0.005*Decay attack, Decay release */
    struct h5_env_s env_click;  /* burst AR^10: 1 ms, 0.2*NoiseDecay+0.1 */
    struct h5_noise_s noise;
    struct h5_svf_s noise_filter;
    struct h5_svf_s out_filter;
    uint32_t phase;          /* 28-bit tone oscillator phase */
    int32_t base_inc;        /* phase28 increment at TonePitch, no bend */
    int32_t bend_q16;        /* pitch sweep depth in 12ths of an octave */
    int32_t noise_pitch_q16; /* noise filter base cutoff, Hz Q16 */
    int32_t tone_gain_q16;   /* 0.9 * NoiseTone^0.7 * (1-Click)^0.7 */
    int32_t noise_gain_q16;  /* 0.3 * (1-NoiseTone)^0.7 * (1-Click)^0.7 */
    int32_t click_gain_q16;  /* 0.9 * Click^0.7 */
    int32_t pf_k50;          /* pre-filter 50 Hz one-pole k, Q30 */
    int32_t pf_k20;          /* pre-filter 20 kHz one-pole k, Q30 */
    int32_t pf_l50;          /* pre-filter 50 Hz low-pass state */
    int32_t pf_l20;          /* pre-filter 20 kHz low-pass state */
    int32_t pf_k338;         /* transient darkening low-pass k, Q30 */
    int32_t pf_l338;         /* transient darkening low-pass state */
    uint8_t active;
};

/* Number of Tom engine instances. H5_VOICE_TOM_1..H5_VOICE_TOM_3 are
 * contiguous in the public enum. */
#define H5_TOM_COUNT 3

/* Tom voice runtime state. The engine keeps its own copies of the parameters
 * it needs per sample so the audio path never reads the parameter matrix. Each
 * Tom instance has its own envelopes, filters, oscillator and noise state,
 * and its own filter-bend depth (the three tunings differ per instance). */
struct h5_tom_s {
    struct h5_env_s env;       /* body AR: 0.005*Decay attack, Decay release */
    struct h5_env_s env_click; /* burst AR^10: 1 ms attack, 0.25*Decay */
    struct h5_noise_s noise;
    struct h5_svf_s noise_filter;
    struct h5_svf_s out_filter;
    uint32_t phase;        /* 28-bit tone oscillator phase */
    int32_t base_inc;      /* phase28 increment at TonePitch, no bend */
    int32_t bend_q16;        /* pitch sweep depth in 12ths of an octave */
    int32_t noise_pitch_q16; /* noise filter base cutoff, Hz Q16 */
    int32_t filter_bend_q16; /* per-instance noise-cutoff bend depth */
    int32_t pf_k50;          /* pre-filter 50 Hz one-pole k, Q30 */
    int32_t pf_k20;          /* pre-filter 20 kHz one-pole k, Q30 */
    int32_t pf_l50;          /* pre-filter 50 Hz low-pass state */
    int32_t pf_l20;          /* pre-filter 20 kHz low-pass state */
    int32_t tone_gain_q16;   /* NoiseTone^0.7 */
    int32_t noise_gain_q16;  /* 0.3 * (1 - NoiseTone)^0.7 */
    int32_t body_gain_q16;   /* (1 - Click)^0.7 */
    int32_t click_gain_q16;  /* Click^0.7 * click scale */
    uint8_t active;
};

/* Snare voice runtime state. */
struct h5_snare_s {
    struct h5_env_s env;       /* body AR: 1 ms attack, Decay release */
    struct h5_env_s env_click; /* transient AR^10: 1 ms attack */
    struct h5_noise_s noise;
    struct h5_svf_s rattle[4];  /* four fixed band-pass resonators */
    struct h5_svf_s out_filter; /* output low-pass at NoisePitch */
    uint32_t phase;            /* 28-bit tone oscillator phase */
    int32_t base_inc;          /* phase28 increment at TonePitch, no bend */
    int32_t bend_q16;          /* pitch sweep depth in 12ths of an octave */
    int32_t noise_pitch_q16;   /* output low-pass base cutoff */
    int32_t pf_k50;            /* pre-filter 50 Hz one-pole k, Q30 */
    int32_t pf_k20;            /* pre-filter 20 kHz one-pole k, Q30 */
    int32_t pf_l50;            /* pre-filter 50 Hz low-pass state */
    int32_t pf_l20;            /* pre-filter 20 kHz low-pass state */
    int32_t tone_gain_q16;     /* NoiseTone^0.7 */
    int32_t noise_gain_q16;    /* 0.3 * (1 - NoiseTone)^0.7 */
    int32_t body_gain_q16;     /* (1 - Click)^0.7 */
    int32_t click_gain_q16;    /* Click^0.7 */
    int32_t sweep_q16;         /* filter-envelope contour depth */
    uint8_t active;
};

/* The concrete context behind the opaque h5_context handle. */
struct h5_context_s {
    uint32_t sample_rate;

    /* Per-voice public parameters, stored as Q16.16 physical values. The
     * mixer controls Volume and Pan live here; the precomputed stereo
     * gains below are derived from them. */
    int32_t voice_params[H5_VOICE_COUNT][H5_PARAM_COUNT];

    /* Mixer stereo gains, Q16: volume * (1 - pan) and volume * pan. Updated
     * when Volume or Pan changes, never on the audio path. */
    int32_t mix_left[H5_VOICE_COUNT];
    int32_t mix_right[H5_VOICE_COUNT];

    /* Voice runtime state, initialized by h5_voice_init_all(). The Toms are
     * three independent instances of the same engine. */
    struct h5_kick_s kick;
    struct h5_tom_s tom[H5_TOM_COUNT];
    struct h5_snare_s snare;
};

/* Kick engine. */
void h5_kick_init(struct h5_kick_s *k, uint32_t sample_rate);
void h5_kick_configure(struct h5_kick_s *k,
    const int32_t params[H5_PARAM_COUNT], uint32_t sample_rate);
void h5_kick_trigger(struct h5_kick_s *k);
int32_t h5_kick_process(struct h5_kick_s *k, uint32_t sample_rate);

/* Tom engine. Times and controls are taken from the context's parameter
 * matrix; the noise generator is seeded per Tom instance and free-runs across
 * triggers so successive hits are not identical. */
void h5_tom_init(struct h5_tom_s *t, h5_voice voice, uint32_t sample_rate);
void h5_tom_configure(struct h5_tom_s *t,
    const int32_t params[H5_PARAM_COUNT], uint32_t sample_rate);
void h5_tom_trigger(struct h5_tom_s *t);
int32_t h5_tom_process(struct h5_tom_s *t, uint32_t sample_rate);

/* Snare engine. */
void h5_snare_init(struct h5_snare_s *s, uint32_t sample_rate);
void h5_snare_configure(struct h5_snare_s *s,
    const int32_t params[H5_PARAM_COUNT], uint32_t sample_rate);
void h5_snare_trigger(struct h5_snare_s *s);
int32_t h5_snare_process(struct h5_snare_s *s, uint32_t sample_rate);

/* Voice helpers used by the lifecycle, parameter and render entry points. */
void h5_voice_init_all(struct h5_context_s *ctx);
void h5_voice_reset_all(struct h5_context_s *ctx);
void h5_voice_configure(struct h5_context_s *ctx, h5_voice voice);
void h5_voice_trigger(struct h5_context_s *ctx, h5_voice voice);

/* Map an instrument trigger to its voice. The instrument must be in range. */
void h5_voice_trigger_instrument(struct h5_context_s *ctx,
    h5_instrument instrument);

int32_t h5_voice_process(struct h5_context_s *ctx, h5_voice voice);

/* Add one instrument's mono Q31 output to the 64-bit stereo accumulators,
 * applying its mixer volume and pan. */
void h5_mix_add(const struct h5_context_s *ctx, h5_instrument instrument,
    int32_t voice_out, int64_t *left, int64_t *right);

/* Recompute one voice's cached stereo gains after Volume or Pan changes. */
void h5_mix_update(struct h5_context_s *ctx, h5_voice voice);

/* Recompute the cached stereo gains for every voice. */
void h5_mix_update_all(struct h5_context_s *ctx);

/* Convert a completed 64-bit Q31 mix accumulator to Q15 with round-half-up
 * and saturation. This is the single conversion in the output stage. */
int16_t h5_mix_to_q15(int64_t sum);

#endif /* HIVE_V_H5_INTERNAL_H */
